// Command gen writes workflows/registry_gen.go: one blank import per directory under workflows/
// (and activities/, once it exists), so creating a directory is all it takes to register a
// workflow. Run it with `go generate ./workflows`; CI fails if the committed file is out of date.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
)

var directory = regexp.MustCompile(`^[a-z][a-z0-9_]{1,62}$`)

func main() {
	log.SetFlags(0)
	// go generate runs in the workflows directory; the module root is its parent.
	module, err := modulePath("../go.mod")
	if err != nil {
		log.Fatal(err)
	}
	var imports []string
	for _, tree := range []string{"workflows", "activities"} {
		names, err := packages(filepath.Join("..", tree))
		if err != nil {
			log.Fatal(err)
		}
		for _, name := range names {
			imports = append(imports, module+"/"+tree+"/"+name)
		}
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by internal/wf/gen; DO NOT EDIT.\n\npackage workflows\n")
	if len(imports) > 0 {
		out.WriteString("\nimport (\n")
		for _, path := range imports {
			fmt.Fprintf(&out, "\t_ %q\n", path)
		}
		out.WriteString(")\n")
	}
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err = os.WriteFile("registry_gen.go", formatted, 0o644); err != nil {
		log.Fatal(err)
	}
}

// packages lists the directories under root that hold Go code, rejecting names that cannot be
// workflow or activity names.
func packages(root string) ([]string, error) {
	entries, err := os.ReadDir(root)
	if os.IsNotExist(err) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var names []string
	for _, entry := range entries {
		name := entry.Name()
		if !entry.IsDir() || name == "testdata" || strings.HasPrefix(name, ".") || strings.HasPrefix(name, "_") {
			continue
		}
		files, err := filepath.Glob(filepath.Join(root, name, "*.go"))
		if err != nil {
			return nil, err
		}
		if len(files) == 0 {
			continue
		}
		if !directory.MatchString(name) {
			return nil, fmt.Errorf("%s/%s: directory names must match %s", root, name, directory)
		}
		names = append(names, name)
	}
	slices.Sort(names)
	return names, nil
}

func modulePath(goMod string) (string, error) {
	content, err := os.ReadFile(goMod)
	if err != nil {
		return "", err
	}
	for _, line := range strings.Split(string(content), "\n") {
		if path, ok := strings.CutPrefix(strings.TrimSpace(line), "module "); ok {
			return strings.TrimSpace(path), nil
		}
	}
	return "", fmt.Errorf("%s has no module line", goMod)
}
